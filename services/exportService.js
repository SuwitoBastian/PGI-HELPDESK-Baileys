    detailSheet.getColumn(2).width = 22;
    detailSheet.getColumn(3).width = 18;
    detailSheet.getColumn(4).width = 20;
    detailSheet.getColumn(5).width = 55;
    detailSheet.getColumn(6).width = 20;
    detailSheet.getColumn(7).width = 15;
    detailSheet.getColumn(8).width = 18;
    detailSheet.getColumn(9).width = 20;

    // ==========================
    // Helper
    // ==========================

    function formatTanggal(value) {

        if (!value) return "-";

        const date = new Date(value);

        if (isNaN(date)) return value;

        return date.toLocaleDateString("id-ID", {

            day: "2-digit",
            month: "2-digit",
            year: "numeric"

        });

    }

    function formatTanggalLengkap(value) {

        if (!value) return "-";

        const date = new Date(value);

        if (isNaN(date)) return value;

        return date.toLocaleDateString("id-ID", {

            day: "2-digit",

            month: "long",

            year: "numeric"

        });

    }

